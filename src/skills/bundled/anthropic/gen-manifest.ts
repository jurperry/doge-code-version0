// One-shot generator for the vendored Anthropic skill set.
//
// Run from anywhere:  bun run src/skills/bundled/anthropic/gen-manifest.ts
//
// Scans the sibling skill directories (each must contain a SKILL.md) and emits:
//   - <skill>.content.ts  per skill: static imports of every vendored file —
//     text files via `with { type: 'text' }` (NEVER rely on Bun's default
//     loaders: .md converts to HTML and unknown extensions resolve to file
//     paths), binaries via the default file loader (returns a real path in
//     source mode, a Bun-embedded asset path in compiled builds)
//   - manifest.ts: registration metadata (name/description extracted from
//     SKILL.md frontmatter at generation time) plus lazy content loaders.
//
// The generated .content.ts modules are dynamically imported only when a
// skill is first invoked, so ~10MB of vendored content never loads at
// startup. Re-run the generator after adding/removing vendored files or
// editing SKILL.md frontmatter (body text is read fresh at invocation).

import { readdir, readFile, stat } from 'fs/promises'
import { basename, extname, join } from 'path'

const ROOT = import.meta.dir

// Extensions inlined as UTF-8 strings. Anything else ships as a binary
// { copyFrom } entry. Unknown-but-actually-text files still work via
// copyFrom (byte-exact copy), so this list only affects which files are
// embedded as strings in compiled builds.
const TEXT_EXTENSIONS = new Set([
  '.md',
  '.txt',
  '.py',
  '.xsd',
  '.xml',
  '.html',
  '.htm',
  '.sh',
  '.js',
  '.mjs',
  '.cjs',
  '.ts',
  '.tsx',
  '.jsx',
  '.json',
  '.css',
  '.toml',
  '.yml',
  '.yaml',
  '.csv',
  '.svg',
])

type DiscoveredFile = {
  /** Skill-relative path with forward slashes (the `files` map key). */
  relPath: string
  isText: boolean
}

async function walk(dir: string, prefix = ''): Promise<DiscoveredFile[]> {
  const out: DiscoveredFile[] = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const relPath = prefix ? `${prefix}/${entry.name}` : entry.name
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      out.push(...(await walk(full, relPath)))
    } else if (entry.isFile()) {
      out.push({
        relPath,
        isText: TEXT_EXTENSIONS.has(extname(entry.name).toLowerCase()),
      })
    }
  }
  return out
}

function toIdentifier(relPath: string, index: number): string {
  const stem = relPath.replace(/\.[^.]+$/, '').replace(/[^a-zA-Z0-9]+/g, '_')
  return `${stem}_${index}`
}

async function main(): Promise<void> {
  const skillDirs: string[] = []
  for (const entry of await readdir(ROOT, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const skillMd = join(ROOT, entry.name, 'SKILL.md')
    try {
      await stat(skillMd)
      skillDirs.push(entry.name)
    } catch {
      // Not a skill directory (e.g. scratch output) — skip.
    }
  }
  skillDirs.sort()

  if (skillDirs.length === 0) {
    throw new Error(`no skill directories with SKILL.md found under ${ROOT}`)
  }

  const manifestEntries: string[] = []

  for (const skill of skillDirs) {
    const files = await walk(join(ROOT, skill))
    const skillMd = files.find(f => f.relPath === 'SKILL.md')
    if (!skillMd) throw new Error(`${skill}: SKILL.md missing`)

    const imports: string[] = [
      `import skillMd from './${skill}/SKILL.md' with { type: 'text' }`,
    ]
    const fileEntries: string[] = []
    const used = new Set<string>(['skillMd'])

    files
      .filter(f => f.relPath !== 'SKILL.md')
      .sort((a, b) => a.relPath.localeCompare(b.relPath))
      .forEach((f, i) => {
        let id = toIdentifier(f.relPath, i)
        while (used.has(id)) id = `${id}_${i}`
        used.add(id)
        const importPath = `./${skill}/${f.relPath}`
        if (f.isText) {
          imports.push(
            `import ${id} from '${importPath}' with { type: 'text' }`,
          )
        } else {
          // Default loader for binary assets resolves to a file path
          // (source tree) or a Bun-embedded asset path (compiled builds).
          imports.push(`import ${id} from '${importPath}'`)
        }
        fileEntries.push(
          f.isText
            ? `  '${f.relPath}': ${id},`
            : `  '${f.relPath}': { copyFrom: ${id} },`,
        )
      })

    const contentFile = join(ROOT, `${skill}.content.ts`)
    const contentSource = `// GENERATED by gen-manifest.ts — do not edit by hand.
// Regenerate: bun run src/skills/bundled/anthropic/gen-manifest.ts

import type { BundledSkillFileContent } from '../../bundledSkills.js'

${imports.join('\n')}

export const SKILL_MD: string = skillMd

export const FILES: Record<string, BundledSkillFileContent> = {
${fileEntries.join('\n')}
}
`
    await Bun.write(contentFile, contentSource)

    // Validate the generated module actually parses and loads before moving
    // on — a broken content module would only surface at first invocation.
    const generated = await import(`./${skill}.content.ts`)
    if (Object.keys(generated.FILES).length !== fileEntries.length) {
      throw new Error(
        `${skill}: generated module exposes ${Object.keys(generated.FILES).length} files, expected ${fileEntries.length}`,
      )
    }

    // Registration metadata comes from SKILL.md frontmatter at generation
    // time, so initBundledSkills() stays pure in-memory (no I/O, no big
    // module loads) — see main.tsx startup comment.
    const { parseFrontmatter } = await import(
      '../../../utils/frontmatterParser.js'
    )
    const { extractDescriptionFromMarkdown } = await import(
      '../../../utils/markdownConfigLoader.js'
    )
    const raw = await readFile(join(ROOT, skill, 'SKILL.md'), 'utf8')
    const { frontmatter, content } = parseFrontmatter(raw)
    const name =
      typeof frontmatter.name === 'string' && frontmatter.name.trim()
        ? frontmatter.name.trim()
        : skill
    const description =
      typeof frontmatter.description === 'string' && frontmatter.description
        ? frontmatter.description
        : extractDescriptionFromMarkdown(content, `Vendored skill: ${skill}`)
    if (name !== skill) {
      console.warn(
        `[gen-manifest] ${skill}: frontmatter name '${name}' differs from directory name`,
      )
    }

    manifestEntries.push(
      `  {\n` +
        `    name: ${JSON.stringify(name)},\n` +
        `    description: ${JSON.stringify(description)},\n` +
        `    load: () => import('./${skill}.content.js'),\n` +
        `  },`,
    )
    console.log(
      `[gen-manifest] ${skill}: ${files.length - 1} files (${
        files.filter(f => f.isText && f.relPath !== 'SKILL.md').length
      } text, ${files.filter(f => !f.isText).length} binary)`,
    )
  }

  const manifestSource = `// GENERATED by gen-manifest.ts — do not edit by hand.
// Regenerate: bun run src/skills/bundled/anthropic/gen-manifest.ts
//
// name/description are extracted from each vendored SKILL.md frontmatter at
// generation time; the lazy load() keeps vendored content out of startup.

import type { BundledSkillFileContent } from '../../bundledSkills.js'

export type AnthropicSkillContentModule = {
  SKILL_MD: string
  FILES: Record<string, BundledSkillFileContent>
}

export type AnthropicSkillManifestEntry = {
  name: string
  description: string
  load: () => Promise<AnthropicSkillContentModule>
}

export const ANTHROPIC_SKILL_MANIFEST: AnthropicSkillManifestEntry[] = [
${manifestEntries.join('\n')}
]
`
  await Bun.write(join(ROOT, 'manifest.ts'), manifestSource)

  const manifest = await import('./manifest.ts')
  const entries = manifest.ANTHROPIC_SKILL_MANIFEST
  if (entries.length !== skillDirs.length || entries.some(e => !e)) {
    throw new Error(
      `generated manifest invalid: ${entries.length} entries (${entries.filter(e => !e).length} holes), expected ${skillDirs.length}`,
    )
  }
  console.log(
    `[gen-manifest] wrote manifest.ts with ${manifestEntries.length} skills`,
  )
}

void main().catch(e => {
  console.error(e)
  process.exit(1)
})
